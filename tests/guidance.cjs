'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
require('../content.js');
require('../interaction.js');
require('../engine.js');
require('../guidance.js');
const {createGuidanceDemo}=require('./guidance-fixture.js');
const I=LifeInteraction, G=LifeGuidance;
test('free exploration changes target, goal and feedback; completion ends help',()=>{
  const run=createGuidanceDemo();
  const describe=()=>G.describe(I.preview(run),{elapsed:20000});
  const before=JSON.stringify(run);
  assert.match(describe().goalText,/两张纸/);
  assert.deepEqual(describe().recommendedObjectIds,['note']);
  assert.equal(JSON.stringify(run),before);
  assert(I.update(run,'demo','act','file-photo'));
  assert.match(describe().goalText,/还有一张便签/);
  assert.match(describe().feedback,/照片已放好/);
  assert.deepEqual(I.preview(run).allowed.map(a=>a.actionId),['file-note']);
  assert(I.update(run,'demo','act','file-note'));
  assert.deepEqual(describe().recommendedObjectIds,[]);
  assert(I.confirm(run,'demo'));
  assert.equal(describe().availableHelp,false);
  assert.equal(describe().hintLevel,0);
  assert.equal(describe().hintText,'');
  assert.match(describe().completionText,/结束/);
});
test('eligible actions alone supply recommendations',()=>{
  const run=createGuidanceDemo();
  const scene=LifeEngine.currentCard(run).interaction;
  scene.objects.note.itemId='lamp';
  run.items.lamp={state:'given'};
  scene.actions[1].experienceId='missing';
  assert.deepEqual(G.describe(I.preview(run),{elapsed:20000}).recommendedObjectIds,[]);
  delete scene.objects.note.itemId;
  delete scene.actions[1].experienceId;
});
test('foreground idle time, invalid input, free progress and instant help',()=>{
  const run=createGuidanceDemo(), clock=G.clock();
  const at=(t,active=true)=>{const v=I.preview(run); return G.describe(v,clock.sample(v,t,active));};
  assert.equal(at(0).hintLevel,0);
  assert.equal(I.update(run,'demo','act','absent'),false);
  assert.equal(at(8000).hintLevel,1);
  at(9000,false);
  assert.equal(at(99000).hintLevel,1);
  assert.equal(at(108000).hintLevel,2);
  assert(I.update(run,'demo','act','file-photo'));
  assert.equal(at(108001).hintLevel,0);
  clock.help();
  assert.match(at(108002).hintText,/收好便签/);
  assert.equal(G.describe(I.preview(run),{elapsed:5},{emphasize:4,explain:6}).hintLevel,1);
});
